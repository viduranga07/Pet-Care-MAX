    private void loadVeterinarians() {

        try {

            List<Veterinarian> veterinarians =
                    veterinarianController.getAllVeterinarians();

            DefaultTableModel model =
                    (DefaultTableModel) tblVeterinarians.getModel();

            // Remove existing rows
            model.setRowCount(0);

            // Add database records
            for (Veterinarian veterinarian : veterinarians) {

                model.addRow(new Object[]{
                    veterinarian.getVeterinarianId(),
                    veterinarian.getFullName(),
                    veterinarian.getSpecialization(),
                    veterinarian.getPhone(),
                    veterinarian.getEmail(),
                    veterinarian.getAvailability(),
                    veterinarian.getStatus()
                });
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Unable to load veterinarian records.\n"
                    + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }
