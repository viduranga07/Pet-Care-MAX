    public void updateVeterinarian() {
        // Button actions are handled by the form controller.
         if (selectedVeterinarianId == 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a veterinarian from the table first."
        );
        return;
    }

    String fullName = txtFullName.getText().trim();
    String specialization = txtSpecialization.getText().trim();
    String phone = txtPhone.getText().trim();
    String email = txtEmail.getText().trim();
    String availability = txtAvailability.getText().trim();
    String status = cmbStatus.getSelectedItem().toString();

    if (fullName.isEmpty() || phone.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Full Name and Phone are required."
        );
        return;
    }

    Veterinarian veterinarian = new Veterinarian(
            selectedVeterinarianId,
            fullName,
            specialization,
            phone,
            email,
            availability,
            status
    );

    try {
        boolean updated = veterinarianController.updateVeterinarian(veterinarian);

        if (updated) {
            JOptionPane.showMessageDialog(
                    this,
                    "Veterinarian updated successfully!"
            );

            clearFields();
            loadVeterinarians();

        } else {
            JOptionPane.showMessageDialog(
                    this,
                    "Failed to update veterinarian."
            );
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );
    }
    }

    public void deleteVeterinarian() {
        // Button actions are handled by the form controller.
          if (selectedVeterinarianId == 0) {
        JOptionPane.showMessageDialog(
                this,
                "Please select a veterinarian from the table first."
        );
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this veterinarian?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
    );

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    try {
        boolean deleted =
                veterinarianController.deleteVeterinarian(
                        selectedVeterinarianId
                );

        if (deleted) {

            JOptionPane.showMessageDialog(
                    this,
                    "Veterinarian deleted successfully!"
            );

            clearFields();
            loadVeterinarians();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Failed to delete veterinarian."
            );
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );
    }
    }

