    public void saveVeterinarian() {
        // Button actions are handled by the form controller.
        String fullName = txtFullName.getText().trim();
String specialization = txtSpecialization.getText().trim();
String phone = txtPhone.getText().trim();
String email = txtEmail.getText().trim();
String availability = txtAvailability.getText().trim();
String status = cmbStatus.getSelectedItem().toString();

if (fullName.isEmpty()) {
    JOptionPane.showMessageDialog(
            this,
            "Please enter veterinarian name.",
            "Validation",
            JOptionPane.WARNING_MESSAGE
    );
    txtFullName.requestFocus();
    return;
}

if (phone.isEmpty()) {
    JOptionPane.showMessageDialog(
            this,
            "Please enter phone number.",
            "Validation",
            JOptionPane.WARNING_MESSAGE
    );
    txtPhone.requestFocus();
    return;
}

try {

    Veterinarian veterinarian = new Veterinarian(
            0,
            fullName,
            specialization,
            phone,
            email,
            availability,
            status
    );

    boolean saved =
            veterinarianController.addVeterinarian(veterinarian);

    if (saved) {

        JOptionPane.showMessageDialog(
                this,
                "Veterinarian saved successfully.",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
        );

        clearFields();
        loadVeterinarians();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "Unable to save veterinarian.",
                "Save Error",
                JOptionPane.ERROR_MESSAGE
        );
    }

} catch (IllegalArgumentException e) {

    JOptionPane.showMessageDialog(
            this,
            e.getMessage(),
            "Validation Error",
            JOptionPane.WARNING_MESSAGE
    );

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            this,
            "An unexpected error occurred:\n" + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
    );
    }
    }
