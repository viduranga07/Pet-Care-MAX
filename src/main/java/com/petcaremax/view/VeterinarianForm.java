    public void searchVeterinarians() {
        // Button actions are handled by the form controller.
         String searchText = txtSearch.getText().trim().toLowerCase();

    if (searchText.isEmpty()) {
        loadVeterinarians();
        return;
    }

    List<Veterinarian> veterinarians =
            veterinarianController.getAllVeterinarians();

    List<Veterinarian> filteredList = veterinarians.stream()
            .filter(v ->
                    String.valueOf(v.getVeterinarianId())
                            .contains(searchText)
                    || v.getFullName().toLowerCase()
                            .contains(searchText)
                    || (v.getSpecialization() != null
                            && v.getSpecialization().toLowerCase()
                                    .contains(searchText))
                    || v.getPhone().toLowerCase()
                            .contains(searchText)
                    || (v.getEmail() != null
                            && v.getEmail().toLowerCase()
                                    .contains(searchText))
                    || (v.getStatus() != null
                            && v.getStatus().toLowerCase()
                                    .contains(searchText))
            )
            .toList();

    DefaultTableModel model =
            (DefaultTableModel) tblVeterinarians.getModel();

    model.setRowCount(0);

    for (Veterinarian v : filteredList) {

        model.addRow(new Object[]{
            v.getVeterinarianId(),
            v.getFullName(),
            v.getSpecialization(),
            v.getPhone(),
            v.getEmail(),
            v.getAvailability(),
            v.getStatus()
        });
    }

    if (filteredList.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "No veterinarian found."
        );
    }
    }
    
     
