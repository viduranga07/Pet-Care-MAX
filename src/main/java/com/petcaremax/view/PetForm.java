    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        String searchText =
                txtSearch.getText()
                        .trim()
                        .toLowerCase();

        if (searchText.isEmpty()) {

            loadPets();

            return;
        }

        try {

            ArrayList<Pet> pets =
                    new ArrayList<>(
                            petController.getAllPets()
                    );

            List<Pet> filtered =
                    pets.stream()

                            .filter(pet ->

                                    String.valueOf(
                                            pet.getPetId()
                                    )
                                    .contains(searchText)

                                    ||

                                    pet.getPetName()
                                            .toLowerCase()
                                            .contains(searchText)

                                    ||

                                    pet.getSpecies()
                                            .toLowerCase()
                                            .contains(searchText)

                                    ||

                                    (
                                        pet.getBreed() != null
                                        &&
                                        pet.getBreed()
                                                .toLowerCase()
                                                .contains(searchText)
                                    )

                                    ||

                                    getOwnerName(
                                            pet.getCustomerId()
                                    )
                                    .toLowerCase()
                                    .contains(searchText)

                            )

                            .collect(
                                    Collectors.toList()
                            );

            currentPets =
                    new ArrayList<>(filtered);

            displayPets(filtered);

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error searching pets:\n"
                    + e.getMessage(),
                    "Search Error",
                    JOptionPane.ERROR_MESSAGE
            );

            e.printStackTrace();
        }
    }


    // ============================================================
    // LOAD CUSTOMERS
    // ============================================================

    private void loadCustomers() {

        try {

            customers =
                    new ArrayList<>(
                            customerController.getAllCustomers()
                    );

            cmbOwner.removeAllItems();

            for (Customer customer : customers) {

                cmbOwner.addItem(
                        customer.getFullName()
                );
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Unable to load owners:\n"
                    + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );

            e.printStackTrace();
        }
    }


    // ============================================================
    // LOAD PETS
    // ============================================================

    private void loadPets() {

        try {

            currentPets =
                    new ArrayList<>(
                            petController.getAllPets()
                    );

            displayPets(currentPets);

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    "Unable to load pets:\n"
                    + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );

            e.printStackTrace();
        }
    }


    // ============================================================
    // DISPLAY PETS IN TABLE
    // ============================================================

    private void displayPets(
            List<Pet> pets
    ) {

        DefaultTableModel model =
                (DefaultTableModel) tblPets.getModel();

        model.setRowCount(0);

        for (Pet pet : pets) {

            model.addRow(
                    new Object[]{

                        pet.getPetId(),

                        pet.getPetName(),

                        pet.getSpecies(),

                        pet.getBreed() == null
                                ? ""
                                : pet.getBreed(),

                        pet.getGender(),

                        pet.getDateOfBirth() == null
                                ? ""
                                : pet.getDateOfBirth(),

                        pet.getWeight() == null
                                ? ""
                                : pet.getWeight(),

                        getOwnerName(
                                pet.getCustomerId()
                        ),

                        pet.getNotes() == null
                                ? ""
                                : pet.getNotes()
                    }
            );
        }
    }


    // ============================================================
    // GET OWNER NAME
    // ============================================================

    private String getOwnerName(
            int customerId
    ) {

        return customers.stream()

                .filter(customer ->
                        customer.getCustomerId()
                        == customerId
                )

                .map(Customer::getFullName)

                .findFirst()

                .orElse("Unknown");
    }


    // ============================================================
    // LOAD SELECTED PET
    // ============================================================

    private void loadSelectedPet() {

        int row =
                tblPets.getSelectedRow();

        if (row == -1) {
            return;
        }

        if (row >= currentPets.size()) {
            return;
        }

        Pet pet =
                currentPets.get(row);


        txtPetName.setText(
                pet.getPetName()
        );


        cmbSpecies.setSelectedItem(
                pet.getSpecies()
        );


        txtBreed.setText(
                pet.getBreed() == null
                        ? ""
                        : pet.getBreed()
        );


        cmbGender.setSelectedItem(
                pet.getGender()
        );


        txtDateOfBirth.setText(
                pet.getDateOfBirth() == null
                        ? ""
                        : pet.getDateOfBirth().toString()
        );


        txtWeight.setText(
                pet.getWeight() == null
                        ? ""
                        : pet.getWeight().toString()
        );


        txtNotes.setText(
                pet.getNotes() == null
                        ? ""
                        : pet.getNotes()
        );


        selectOwner(
                pet.getCustomerId()
        );
    }


    // ============================================================
    // SELECT OWNER
    // ============================================================

    private void selectOwner(
            int customerId
    ) {

        for (int i = 0;
                i < customers.size();
                i++) {

            Customer customer =
                    customers.get(i);

            if (customer.getCustomerId()
                    == customerId) {

                cmbOwner.setSelectedIndex(i);

                return;
            }
        }
    }


    // ============================================================
    // CLEAR FIELDS
    // ============================================================

    private void clearFields() {

        txtPetName.setText("");

        txtBreed.setText("");

        txtDateOfBirth.setText("");

        txtWeight.setText("");

        txtNotes.setText("");

        txtSearch.setText("");


        if (cmbSpecies.getItemCount() > 0) {

            cmbSpecies.setSelectedIndex(0);
        }


        if (cmbGender.getItemCount() > 0) {

            cmbGender.setSelectedIndex(0);
        }


        if (cmbOwner.getItemCount() > 0) {

            cmbOwner.setSelectedIndex(0);
        }


        tblPets.clearSelection();

        txtPetName.requestFocus();
    }


