    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
         int row = tblPets.getSelectedRow();
try {

            String petName =
                    txtPetName.getText().trim();

            String species =
                    cmbSpecies.getSelectedItem() == null
                            ? ""
                            : cmbSpecies.getSelectedItem().toString();

            String breed =
                    txtBreed.getText().trim();

            String gender =
                    cmbGender.getSelectedItem() == null
                            ? ""
                            : cmbGender.getSelectedItem().toString();

            String dobText =
                    txtDateOfBirth.getText().trim();

            String weightText =
                    txtWeight.getText().trim();

            String notes =
                    txtNotes.getText().trim();


            // ----------------------------------------------------
            // Get selected owner
            // ----------------------------------------------------

            int ownerIndex =
                    cmbOwner.getSelectedIndex();

            if (ownerIndex < 0
                    || ownerIndex >= customers.size()) {

                JOptionPane.showMessageDialog(
                        this,
                        "Please select an owner.",
                        "Validation Error",
                        JOptionPane.WARNING_MESSAGE
                );

                return;
            }

            Customer selectedCustomer =
                    customers.get(ownerIndex);

            int customerId =
                    selectedCustomer.getCustomerId();


            // ----------------------------------------------------
            // Date of birth
            // ----------------------------------------------------

            LocalDate dateOfBirth = null;

            if (!dobText.isEmpty()) {

                try {

                    dateOfBirth =
                            LocalDate.parse(dobText);

                } catch (DateTimeParseException e) {

                    JOptionPane.showMessageDialog(
                            this,
                            "Invalid date format.\n"
                            + "Please use YYYY-MM-DD.",
                            "Validation Error",
                            JOptionPane.WARNING_MESSAGE
                    );

                    return;
                }
            }


            // ----------------------------------------------------
            // Weight
            // ----------------------------------------------------

            Double weight = null;

            if (!weightText.isEmpty()) {

                try {

                    weight =
                            Double.parseDouble(weightText);

                } catch (NumberFormatException e) {

                    JOptionPane.showMessageDialog(
                            this,
                            "Weight must be a valid number.",
                            "Validation Error",
                            JOptionPane.WARNING_MESSAGE
                    );

                    return;
                }
            }


            // ----------------------------------------------------
            // Create Pet object
            // ----------------------------------------------------

            Pet pet = new Pet(
                    0,
                    customerId,
                    petName,
                    species,
                    breed,
                    gender,
                    dateOfBirth,
                    weight,
                    notes
            );


            // ----------------------------------------------------
            // Save
            // ----------------------------------------------------

            boolean saved =
                    petController.addPet(pet);

            if (saved) {

                JOptionPane.showMessageDialog(
                        this,
                        "Pet saved successfully.",
                        "Success",
                        JOptionPane.INFORMATION_MESSAGE
                );

                clearFields();

                loadPets();

            } else {

                JOptionPane.showMessageDialog(
                        this,
                        "Pet could not be saved.",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
            }

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE
            );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    "An unexpected error occurred:\n"
                    + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );

            e.printStackTrace();
        }
    

    }//GEN-LAST:event_btnSaveActionPerformed

